import Foundation

let start = Date(timeIntervalSince1970: 1000)
var engine = TimerEngine()
func expect(_ condition: @autoclosure () -> Bool, _ name: String) {
    guard condition() else { fatalError("FAIL: \(name)") }
    print("PASS: \(name)")
}
engine.tick(now: start, mouseMoved: false, idle: 0)
expect(engine.phase == .waiting, "No mouse activity means no countdown")
engine.tick(now: start, mouseMoved: true, idle: 0)
expect(engine.phase == .focusing && engine.remaining(now: start) == 1200, "Mouse starts 20 minute cycle")
engine.tick(now: start.addingTimeInterval(1199), mouseMoved: true, idle: 0)
expect(engine.phase == .focusing, "No early reminder")
engine.tick(now: start.addingTimeInterval(1200), mouseMoved: false, idle: 1)
expect(engine.phase == .reminding, "Deadline raises reminder")
engine.snooze(now: start)
expect(engine.remaining(now: start) == 300, "Snooze is 5 minutes")
engine.startBreak(now: start)
engine.tick(now: start.addingTimeInterval(299), mouseMoved: true, idle: 0)
expect(engine.phase == .resting, "Mouse activity does not cancel break")
engine.tick(now: start.addingTimeInterval(300), mouseMoved: false, idle: 300)
expect(engine.phase == .waiting && engine.completedBreaks == 1, "Completed break waits for fresh movement")
engine.tick(now: start.addingTimeInterval(301), mouseMoved: false, idle: 0)
expect(engine.phase == .waiting && engine.completedBreaks == 1, "No duplicate completion")
engine.tick(now: start, mouseMoved: true, idle: 0)
engine.tick(now: start.addingTimeInterval(400), mouseMoved: false, idle: 300)
expect(engine.phase == .waiting, "Five idle minutes reset focus")
engine.tick(now: start, mouseMoved: true, idle: 0)
engine.setInterval(1800, now: start.addingTimeInterval(10))
expect(engine.remaining(now: start.addingTimeInterval(10)) == 1800, "Interval change restarts countdown")
engine.togglePause()
engine.tick(now: start.addingTimeInterval(9999), mouseMoved: true, idle: 0)
expect(engine.phase == .paused, "Paused timer never reminds")
engine.togglePause()
expect(engine.phase == .waiting, "Resume waits for mouse movement")
engine.tick(now: start, mouseMoved: true, idle: 0)
engine.wake(now: start.addingTimeInterval(9999))
expect(engine.phase == .waiting, "Wake discards stale focus deadline")
engine.startBreak(now: start)
engine.wake(now: start.addingTimeInterval(9999))
expect(engine.phase == .waiting && engine.completedBreaks == 2, "Rest can finish during sleep")
engine.startBreak(now: start)
engine.reset()
expect(engine.phase == .waiting && engine.completedBreaks == 2, "Ending a break early grants no completion")
print("All timer behavior checks passed.")
